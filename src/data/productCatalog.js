/* ==========================================================
   OPTIONAL HELPERS
========================================================== */

export function getProductBySlug(slug) {
  return productCatalog.find(
    (product) =>
      product.slug === slug,
  );
}


export function getRelatedProducts(
  currentSlug,
  limit = 2,
) {
  return productCatalog
    .filter(
      (product) =>
        product.slug !== currentSlug,
    )
    .slice(0, limit);
}